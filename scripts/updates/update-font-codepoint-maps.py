#!/usr/bin/env python3
# ============================================================================ #
# ++++++++++++++++++++++++ FONT CODEPOINT MAP UPDATER ++++++++++++++++++++++++ #
# ============================================================================ #
"""Report or regenerate terminal font code point maps from their declarations.

Usage:
  scripts/updates/update-font-codepoint-maps.py --check [--map NAME]... [--manifest PATH]
  scripts/updates/update-font-codepoint-maps.py --apply [--map NAME]... [--manifest PATH]

Each map in the manifest (default: font-codepoint-maps.toml beside this file)
names a primary font, an overlay font and the code points the overlay should
draw; its comments describe the selection rule. The result is written as exact
code point ranges, because a terminal may use a mapped font without checking
that it has the glyph (Kitty does), and a mapping takes precedence over the
colour emoji font (Kitty and Ghostty both). Gaps between ranges are bridged
only across unassigned code points.

Fonts, the Unicode Character Database and fc-query are nixpkgs packages
resolved through the flake's lock (`nix build --inputs-from`), so the output
depends only on the checkout. Generated files carry a marker line; an existing
file without it is never overwritten. Writes are atomic.

Exit status: 0 up to date or applied, 1 out of date (--check), 2 usage,
manifest, environment or source error.
"""

import sys

if sys.version_info < (3, 11):
    sys.exit(
        "update-font-codepoint-maps requires Python 3.11 or newer (tomllib)."
    )

import argparse
import bisect
import json
import os
import re
import shutil
import subprocess
import tempfile
from dataclasses import dataclass
from pathlib import Path

import tomllib

# A checkout is not a place for bytecode caches.
sys.dont_write_bytecode = True

ROOT = Path(__file__).resolve().parents[2]
SCRIPT = Path(__file__).resolve().relative_to(ROOT).as_posix()
DEFAULT_MANIFEST = (
    Path(__file__).resolve().with_name("font-codepoint-maps.toml")
)
MARKER = f"# Generated by {SCRIPT}"

UCD_PACKAGE = "unicode-character-database"
FONTCONFIG_PACKAGE = "fontconfig.bin"
NIX_TIMEOUT = 900
FC_QUERY_TIMEOUT = 120
RANGES_PER_LINE = 8
MAX_CODEPOINT = 0x10FFFF
# Controls, surrogates and private use: never meaningful to route by family.
UNMAPPABLE_CATEGORIES = {"Cc", "Cs", "Co"}

NAME_RE = re.compile(r"[a-z0-9][a-z0-9-]*")
FAMILY_RE = re.compile(r"[A-Za-z0-9][A-Za-z0-9 ._+-]*[A-Za-z0-9]")
PACKAGE_RE = re.compile(
    r"[A-Za-z_][A-Za-z0-9_+-]*(\.[A-Za-z_][A-Za-z0-9_+-]*)*"
)
CODEPOINT_RE = re.compile(r"U\+([0-9A-Fa-f]{4,6})")


class UpdateError(Exception):
    """A manifest, environment or source problem that stops the update."""


@dataclass(frozen=True)
class FontSource:
    """Font files inside one nixpkgs package output."""

    package: str
    files: str


@dataclass(frozen=True)
class Output:
    """One generated file and the configuration syntax it is written in."""

    path: Path
    format: str


@dataclass(frozen=True)
class CodepointMap:
    """A validated [[map]] declaration from the manifest."""

    name: str
    family: str
    overlay: FontSource
    primary: FontSource
    prefer: tuple[tuple[int, int], ...]
    outputs: tuple[Output, ...]


@dataclass(frozen=True)
class UnicodeData:
    """The parts of the Unicode Character Database the selection needs."""

    assigned: frozenset[int]
    unmappable: frozenset[int]
    emoji_presentation: frozenset[int]
    version: str


def render_kitty(family, spec):
    """Return one Kitty `symbol_map` line for the given range specifiers."""
    return f"symbol_map {','.join(spec)} {family}"


def render_ghostty(family, spec):
    """Return one Ghostty `font-codepoint-map` line for the range specifiers."""
    return f"font-codepoint-map = {','.join(spec)}={family}"


FORMATS = {"kitty": render_kitty, "ghostty": render_ghostty}


# ----- MANIFEST ---------------------------------------------------------------


def parse_codepoint(text):
    """Parse `U+XXXX` (4 to 6 hex digits) into a code point."""
    match = CODEPOINT_RE.fullmatch(text)
    if not match:
        raise UpdateError(f"invalid code point {text!r}; expected U+XXXX")
    value = int(match[1], 16)
    if value > MAX_CODEPOINT:
        raise UpdateError(f"code point {text} is beyond U+10FFFF")
    return value


def parse_range(text):
    """Parse `U+XXXX` or `U+XXXX-U+YYYY` into an inclusive (low, high) pair."""
    if not isinstance(text, str):
        raise UpdateError(f"range {text!r} must be a string")
    low_text, sep, high_text = text.partition("-")
    low = parse_codepoint(low_text)
    high = parse_codepoint(high_text) if sep else low
    if high < low:
        raise UpdateError(f"range {text} is reversed")
    return low, high


def require_keys(table, required, where):
    """Reject a manifest table with missing or unknown keys."""
    if not isinstance(table, dict):
        raise UpdateError(f"{where} must be a table")
    problems = [
        f"{label} {sorted(keys)}"
        for label, keys in (
            ("missing", required - table.keys()),
            ("unknown", table.keys() - required),
        )
        if keys
    ]
    if problems:
        raise UpdateError(f"{where}: {', '.join(problems)}")


def require_string(table, key, pattern, where):
    """Return table[key] if it is a string that fully matches pattern."""
    value = table[key]
    if not isinstance(value, str) or not pattern.fullmatch(value):
        raise UpdateError(f"{where}.{key} = {value!r} is not allowed")
    return value


def parse_font_source(table, where):
    """Validate a font source table: a package attribute and a relative glob."""
    require_keys(table, {"package", "files"}, where)
    package = require_string(table, "package", PACKAGE_RE, where)
    files = table["files"]
    parts = Path(files).parts if isinstance(files, str) else ()
    if not parts or Path(files).is_absolute() or ".." in parts:
        raise UpdateError(f"{where}.files = {files!r} must be a relative glob")
    return FontSource(package, files)


def resolve_output_path(text, root, where):
    """Resolve an output path, which must stay inside the repository root."""
    if not isinstance(text, str) or not text or Path(text).is_absolute():
        raise UpdateError(f"{where}.path = {text!r} must be a relative path")
    path = (root / text).resolve()
    if not path.is_relative_to(root) or path == root:
        raise UpdateError(f"{where}.path = {text!r} leaves the repository")
    return path


def parse_map(table, root, where):
    """Validate one [[map]] table into a CodepointMap."""
    require_keys(
        table,
        {"name", "family", "overlay", "primary", "prefer", "outputs"},
        where,
    )
    name = require_string(table, "name", NAME_RE, where)
    family = require_string(table, "family", FAMILY_RE, where)
    if not isinstance(table["prefer"], list):
        raise UpdateError(f"{where}.prefer must be an array")
    if not isinstance(table["outputs"], list) or not table["outputs"]:
        raise UpdateError(f"{where}.outputs must be a non-empty array")
    outputs = []
    for index, entry in enumerate(table["outputs"]):
        at = f"{where}.outputs[{index}]"
        require_keys(entry, {"path", "format"}, at)
        if entry["format"] not in FORMATS:
            raise UpdateError(f"{at}.format must be one of {sorted(FORMATS)}")
        outputs.append(
            Output(
                resolve_output_path(entry["path"], root, at), entry["format"]
            )
        )
    return CodepointMap(
        name=name,
        family=family,
        overlay=parse_font_source(table["overlay"], f"{where}.overlay"),
        primary=parse_font_source(table["primary"], f"{where}.primary"),
        prefer=tuple(parse_range(r) for r in table["prefer"]),
        outputs=tuple(outputs),
    )


def load_manifest(path, root):
    """Read and validate the manifest; names and output paths must be unique."""
    try:
        data = tomllib.loads(path.read_text(encoding="utf-8"))
    except (OSError, UnicodeDecodeError, tomllib.TOMLDecodeError) as error:
        raise UpdateError(f"cannot read manifest {path}: {error}") from error
    require_keys(data, {"map"}, "manifest")
    if not isinstance(data["map"], list) or not data["map"]:
        raise UpdateError("manifest: [[map]] must declare at least one map")
    maps = [parse_map(t, root, f"map[{i}]") for i, t in enumerate(data["map"])]
    names = [m.name for m in maps]
    paths = [o.path for m in maps for o in m.outputs]
    if len(set(names)) != len(names):
        raise UpdateError("manifest: map names must be unique")
    if len(set(paths)) != len(paths):
        raise UpdateError("manifest: an output path is declared twice")
    return maps


# ----- SOURCES ----------------------------------------------------------------


def run(command, timeout):
    """Run a command without a shell and return its stdout; fail with stderr."""
    try:
        result = subprocess.run(
            command,
            capture_output=True,
            text=True,
            timeout=timeout,
            check=False,
        )
    except (OSError, subprocess.TimeoutExpired) as error:
        raise UpdateError(f"{command[0]}: {error}") from error
    if result.returncode != 0:
        detail = result.stderr.strip().splitlines()[-5:]
        raise UpdateError(
            f"{' '.join(command)} failed:\n  " + "\n  ".join(detail)
        )
    return result.stdout


class Sources:
    """Resolves packages through the flake and caches every lookup."""

    def __init__(self, root):
        """Locate nix and remember the flake whose lock pins nixpkgs."""
        nix = shutil.which("nix")
        if nix is None:
            raise UpdateError("nix is not on PATH")
        self.nix = nix
        self.root = root
        self.packages = {}
        self.charsets = {}
        self._fc_query = None
        self._unicode = None

    def package(self, attribute):
        """Build (or fetch) nixpkgs#attribute and return its only output path."""
        if attribute not in self.packages:
            out = run(
                [
                    self.nix,
                    "build",
                    "--inputs-from",
                    str(self.root),
                    "--no-link",
                    "--json",
                    f"nixpkgs#{attribute}",
                ],
                NIX_TIMEOUT,
            )
            try:
                (result,) = json.loads(out)
                (path,) = result["outputs"].values()
            except (ValueError, KeyError, TypeError) as error:
                raise UpdateError(
                    f"nixpkgs#{attribute}: expected exactly one output"
                ) from error
            path = Path(path)
            if not path.is_absolute() or not path.is_dir():
                raise UpdateError(
                    f"nixpkgs#{attribute}: {path} is not a directory"
                )
            self.packages[attribute] = path
        return self.packages[attribute]

    def fc_query(self):
        """Return the pinned fc-query executable."""
        if self._fc_query is None:
            path = self.package(FONTCONFIG_PACKAGE) / "bin/fc-query"
            if not os.access(path, os.X_OK):
                raise UpdateError(f"{path} is not executable")
            self._fc_query = path
        return self._fc_query

    def font_files(self, source):
        """Return the font files a FontSource matches, all inside its package."""
        package = self.package(source.package)
        files = sorted(p for p in package.glob(source.files) if p.is_file())
        if not files:
            raise UpdateError(
                f"nixpkgs#{source.package}: no file matches {source.files}"
            )
        for path in files:
            if not path.resolve().is_relative_to(package.resolve()):
                raise UpdateError(
                    f"{path} resolves outside nixpkgs#{source.package}"
                )
        return files

    def charset(self, font):
        """Return the code points one font file maps to a glyph."""
        if font not in self.charsets:
            text = run(
                [str(self.fc_query()), "-f", "%{charset}", str(font)],
                FC_QUERY_TIMEOUT,
            )
            self.charsets[font] = parse_charset(text, str(font))
        return self.charsets[font]

    def coverage(self, source):
        """Return the code points present in every file of a FontSource.

        A terminal loads the family in each style it needs, so a code point is
        only safe when no style lacks it.
        """
        return frozenset(
            set.intersection(
                *(self.charset(f) for f in self.font_files(source))
            )
        )

    def unicode(self):
        """Return the pinned Unicode Character Database tables."""
        if self._unicode is None:
            package = self.package(UCD_PACKAGE)
            ucd = package / "share/unicode"
            assigned, unmappable = parse_unicode_data(ucd / "UnicodeData.txt")
            self._unicode = UnicodeData(
                assigned=assigned,
                unmappable=unmappable,
                emoji_presentation=parse_property(
                    ucd / "emoji/emoji-data.txt", "Emoji_Presentation"
                ),
                version=store_name(package),
            )
        return self._unicode


def store_name(path):
    """Return a store path's name without its hash (`name-version`)."""
    name = path.name
    head, sep, tail = name.partition("-")
    return tail if sep and len(head) == 32 else name


def parse_charset(text, where):
    """Parse fc-query's %{charset} (space-separated hex ranges) into a set."""
    codepoints = set()
    for token in text.split():
        try:
            low, high = parse_hex_range(token, "-")
        except ValueError as error:
            raise UpdateError(
                f"{where}: bad charset token {token!r}"
            ) from error
        codepoints.update(range(low, high + 1))
    if not codepoints:
        raise UpdateError(f"{where}: empty character set")
    return codepoints


def parse_hex_range(text, separator):
    """Parse `XXXX` or `XXXX<separator>YYYY` hex into an inclusive pair."""
    low_text, sep, high_text = text.partition(separator)
    low = int(low_text, 16)
    high = int(high_text, 16) if sep else low
    if not 0 <= low <= high <= MAX_CODEPOINT:
        raise ValueError(f"range {text!r} out of order or out of bounds")
    return low, high


def read_lines(path):
    """Yield (line number, line) of a UCD text file."""
    try:
        text = path.read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError) as error:
        raise UpdateError(f"cannot read {path}: {error}") from error
    yield from enumerate(text.splitlines(), start=1)


def parse_unicode_data(path):
    """Return (assigned, unmappable) code points from UnicodeData.txt.

    `<..., First>`/`<..., Last>` pairs denote ranges; unmappable means general
    category Cc, Cs or Co.
    """
    assigned, unmappable, first = set(), set(), None
    for number, line in read_lines(path):
        fields = line.split(";")
        try:
            if len(fields) != 15:
                raise ValueError("expected 15 fields")
            codepoint = parse_hex_range(fields[0], "..")[0]
        except ValueError as error:
            raise UpdateError(f"{path}:{number}: {error}") from error
        name, category = fields[1], fields[2]
        if name.endswith(", First>"):
            first = codepoint
            continue
        if name.endswith(", Last>"):
            if first is None or first > codepoint:
                raise UpdateError(f"{path}:{number}: Last without First")
            block = range(first, codepoint + 1)
            first = None
        else:
            block = range(codepoint, codepoint + 1)
        assigned.update(block)
        if category in UNMAPPABLE_CATEGORIES:
            unmappable.update(block)
    if first is not None or len(assigned) < 100_000:
        raise UpdateError(f"{path}: truncated or not UnicodeData.txt")
    return frozenset(assigned), frozenset(unmappable)


def parse_property(path, name):
    """Return the code points that have a binary property in a UCD data file."""
    codepoints = set()
    for number, line in read_lines(path):
        fields = [f.strip() for f in line.split("#", 1)[0].split(";")]
        if len(fields) < 2 or fields[1] != name:
            continue
        try:
            low, high = parse_hex_range(fields[0], "..")
        except ValueError as error:
            raise UpdateError(f"{path}:{number}: {error}") from error
        codepoints.update(range(low, high + 1))
    if not codepoints:
        raise UpdateError(f"{path}: no code point has {name}")
    return frozenset(codepoints)


# ----- SELECTION --------------------------------------------------------------


def in_ranges(codepoint, ranges):
    """Tell whether codepoint lies in any inclusive (low, high) range."""
    return any(low <= codepoint <= high for low, high in ranges)


def select(overlay, primary, unicode, prefer):
    """Return the code points the overlay font should draw (see the manifest)."""
    return {
        cp
        for cp in overlay
        if cp in unicode.assigned
        and cp not in unicode.unmappable
        and cp not in unicode.emoji_presentation
        and (cp not in primary or in_ranges(cp, prefer))
    }


def compact(selected, assigned):
    """Group selected code points into sorted inclusive ranges.

    Two neighbours merge when every code point between them is unassigned:
    such a code point never reaches the renderer, so covering it is harmless
    and keeps the map short.
    """
    assigned_sorted = sorted(assigned)
    ranges = []
    for cp in sorted(selected):
        if ranges:
            gap_start = ranges[-1][1] + 1
            first_assigned = bisect.bisect_left(assigned_sorted, gap_start)
            if (
                first_assigned == len(assigned_sorted)
                or assigned_sorted[first_assigned] >= cp
            ):
                ranges[-1][1] = cp
                continue
        ranges.append([cp, cp])
    return [(low, high) for low, high in ranges]


def range_spec(low, high):
    """Format an inclusive range as `U+XXXX` or `U+XXXX-U+YYYY`."""
    return f"U+{low:04X}" if low == high else f"U+{low:04X}-U+{high:04X}"


def render(fmt, codepoint_map, ranges, sources):
    """Return the text of one generated file in the given format."""
    if not ranges:
        raise UpdateError(
            f"map {codepoint_map.name}: nothing to route to the overlay"
        )
    spec = [range_spec(low, high) for low, high in ranges]
    line = FORMATS[fmt]
    lines = [
        f"{MARKER} (map {codepoint_map.name}); do not edit.",
        f"# Sources: {', '.join(sources)}.",
        "",
    ]
    for start in range(0, len(spec), RANGES_PER_LINE):
        lines.append(
            line(codepoint_map.family, spec[start : start + RANGES_PER_LINE])
        )
    return "\n".join(lines) + "\n"


def generate(codepoint_map, sources):
    """Return {output path: text} for one map."""
    unicode = sources.unicode()
    overlay = sources.coverage(codepoint_map.overlay)
    primary = sources.coverage(codepoint_map.primary)
    if not set(range(0x20, 0x7F)) <= primary:
        raise UpdateError(
            f"map {codepoint_map.name}: primary font lacks printable ASCII; wrong files?"
        )
    ranges = compact(
        select(overlay, primary, unicode, codepoint_map.prefer),
        unicode.assigned,
    )
    names = [
        store_name(sources.package(codepoint_map.overlay.package)),
        store_name(sources.package(codepoint_map.primary.package)),
        unicode.version,
    ]
    return {
        output.path: render(output.format, codepoint_map, ranges, names)
        for output in codepoint_map.outputs
    }


# ----- OUTPUT -----------------------------------------------------------------


def current_text(path):
    """Return a target's current text, None if absent; refuse foreign files."""
    if path.is_symlink():
        raise UpdateError(f"{path} is a symlink; refusing to follow it")
    if not path.exists():
        return None
    try:
        text = path.read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError) as error:
        raise UpdateError(f"cannot read {path}: {error}") from error
    if not text.startswith(MARKER):
        raise UpdateError(
            f"{path} was not generated by {SCRIPT}; refusing to replace it"
        )
    return text


def write_atomic(path, text):
    """Replace path with text via a synced temporary file in the same directory."""
    path.parent.mkdir(parents=True, exist_ok=True)
    descriptor, temporary = tempfile.mkstemp(
        dir=path.parent, prefix=f".{path.name}."
    )
    try:
        with os.fdopen(descriptor, "w", encoding="utf-8") as handle:
            handle.write(text)
            handle.flush()
            os.fsync(handle.fileno())
        os.chmod(temporary, 0o644)
        os.replace(temporary, path)
    except BaseException:
        Path(temporary).unlink(missing_ok=True)
        raise


def parse_arguments(argv):
    """Parse the command line; argparse exits with status 2 on misuse."""
    parser = argparse.ArgumentParser(
        prog=SCRIPT, description=(__doc__ or "").split("\n\n")[0]
    )
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument(
        "--check", action="store_true", help="report stale files"
    )
    mode.add_argument(
        "--apply", action="store_true", help="rewrite stale files"
    )
    parser.add_argument(
        "--map", action="append", default=[], help="limit to a map name"
    )
    parser.add_argument("--manifest", type=Path, default=DEFAULT_MANIFEST)
    return parser.parse_args(argv)


def main(argv):
    """Entry point; returns the process exit status."""
    arguments = parse_arguments(argv)
    try:
        maps = load_manifest(arguments.manifest, ROOT)
        unknown = set(arguments.map) - {m.name for m in maps}
        if unknown:
            raise UpdateError(f"unknown map(s): {', '.join(sorted(unknown))}")
        if arguments.map:
            maps = [m for m in maps if m.name in arguments.map]
        sources = Sources(ROOT)
        wanted = {}
        for codepoint_map in maps:
            wanted.update(generate(codepoint_map, sources))
        stale = {p: t for p, t in wanted.items() if current_text(p) != t}
        if arguments.apply:
            for path, text in stale.items():
                write_atomic(path, text)
                print(f"Wrote {path.relative_to(ROOT)}.")
    except UpdateError as error:
        print(f"{SCRIPT}: {error}", file=sys.stderr)
        return 2
    if arguments.check and stale:
        for path in stale:
            print(
                f"{path.relative_to(ROOT)} is out of date; run with --apply."
            )
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
